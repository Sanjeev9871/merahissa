/**
 * The guide in the requested language, falling back to English when the Hindi
 * translation is not ready yet. `translated` is false in that case so the page
 * can say so rather than silently serving English to a Hindi reader.
 */
export function guideBySlugLocalized(
  slug: string,
  locale: 'en' | 'hi',
): { guide: Guide; translated: boolean } | undefined {
  const english = GUIDES.find((g) => g.slug === slug);
  if (!english) return undefined;
  if (locale === 'en') return { guide: english, translated: true };

  const hindi = GUIDES_HI[slug];
  return hindi ? { guide: hindi, translated: true } : { guide: english, translated: false };
}

/** Guide list for the index page, in the requested language where available. */
export function guidesForLocale(locale: 'en' | 'hi'): Array<Guide & { translated: boolean }> {
  return GUIDES.map((g) => {
    if (locale === 'en') return { ...g, translated: true };
    const hindi = GUIDES_HI[g.slug];
    return hindi ? { ...hindi, translated: true } : { ...g, translated: false };
  });
}
